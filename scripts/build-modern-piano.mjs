// Optional, explicit regeneration only. npm install/build never fetches songs.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {parseMidi,clipEvents,encodeMidi,guideGroups} from '../src/piano-music.js';

const root=fileURLToPath(new URL('../',import.meta.url));
const manifest=JSON.parse(await fs.readFile(path.join(root,'data/piano-modern-7.37.json'),'utf8'));
const index=process.argv.indexOf('--source-dir'),sourceDir=index>=0?process.argv[index+1]:null;
if(!sourceDir&&!process.argv.includes('--fetch'))throw Error('Use --source-dir PATH or --fetch. Ready scores are already bundled.');
const sha=b=>createHash('sha256').update(b).digest('hex');
const output=path.join(root,'public/piano/modern-7.37');
await fs.mkdir(output,{recursive:true});
const scores=[],report=[];
for(const track of manifest.tracks){
 let bytes;
 if(sourceDir)bytes=await fs.readFile(path.join(sourceDir,track.inputFile));
 else{
  const response=await fetch(track.downloadUrl,{signal:AbortSignal.timeout(30000)});
  if(!response.ok)throw Error('Source download failed: '+track.id+' / '+response.status);
  bytes=new Uint8Array(await response.arrayBuffer());
 }
 if(sha(bytes)!==track.sourceSha256)throw Error('Source checksum mismatch: '+track.id);
 const parsed=parseMidi(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),{trackHands:track.trackHands});
 if(parsed.duration<track.clipStart+30)throw Error('Source is shorter than its selected 30 seconds: '+track.id);
 const clip=clipEvents(parsed.events,track.clipStart,30);
 if(clip.length<30||guideGroups(clip,'right').length<8)throw Error('Missing melody: '+track.id);
 const midi=encodeMidi(clip,{tempo:parsed.bpm});
 // Exported files use channel 1 for the melody and channel 2 for the bass.
 // Keep the actual score staves, including notes crossing middle C.
 const final=parseMidi(midi.buffer,{channelHands:{0:'right',1:'left'}}).events;
 await fs.writeFile(path.join(output,track.id+'.mid'),midi);
 const rows=final.map(n=>[+n.time.toFixed(5),n.midi,+n.duration.toFixed(5),+n.velocity.toFixed(5),n.hand==='left'?1:0]);
 scores.push({id:track.id,title:track.title,artist:track.artist,year:track.year,language:track.language,
  mood:track.mood,kind:'ready',duration:30,bpm:parsed.bpm,key:'Do–Re–Mi',difficulty:guideGroups(final,'right').length>90?'Ilg‘or':'O‘rta',
  aliases:track.aliases,sourceUrl:track.sourceUrl,sourceMidi:'/piano/modern-7.37/'+track.id+'.mid',
  credit:'Free Piano Tutorials · tayyor piano aranjirovkasidan 30 soniyalik parcha.',
  description:'Do–Re–Mi bilan nota-ba-nota o‘rganing. Avval tinglang, keyin yoritilgan klavishlarni bosib chaling.',rows});
 report.push({id:track.id,title:track.title,artist:track.artist,notes:final.length,bpm:parsed.bpm,
  rightHandSteps:guideGroups(final,'right').length,leftHandSteps:guideGroups(final,'left').length,
  sourceNotes:parsed.events.length,sourceDuration:parsed.duration,sourceSha256:sha(bytes),
  clipSha256:sha(midi),clipBytes:midi.length,clipStart:track.clipStart,clipLength:30,sourceUrl:track.sourceUrl,
  handAssignment:'MIDI score staff 0: right; staff 1: left. Export channels 0: right, 1: left.',
  inventedMelody:false,generatedAccompaniment:false});
}
const js='// Generated by scripts/build-modern-piano.mjs. Sources: data/piano-modern-7.37.json.\n'
 +'// Original composition and arrangement rights remain with their rights holders.\n'
 +'const scores='+JSON.stringify(scores)+';\n'
 +"export const MODERN_SONGS=scores.map(({rows,...track})=>({...track,events:rows.map(([time,midi,duration,velocity,left])=>({time,midi,duration,velocity,hand:left?'left':'right'}))}));\n";
await fs.writeFile(path.join(root,'src/piano-modern-ready.js'),js);
await fs.writeFile(path.join(output,'manifest.json'),JSON.stringify({checkedAt:manifest.checkedAt,source:manifest.source,rights:manifest.rights,tracks:report},null,2)+'\n');
console.log(JSON.stringify({tracks:scores.length,notes:report.reduce((a,t)=>a+t.notes,0),midiBytes:report.reduce((a,t)=>a+t.clipBytes,0),scoreModuleBytes:Buffer.byteLength(js),report}));
