// Optional regeneration. Normal install/build uses the bundled scores offline.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {parseMidi,clipEvents,encodeMidi,guideGroups} from '../src/piano-music.js';

const root=fileURLToPath(new URL('../',import.meta.url));
const manifest=JSON.parse(await fs.readFile(path.join(root,'data/piano-focus-7.38.json'),'utf8'));
const index=process.argv.indexOf('--source-dir'),sourceDir=index>=0?process.argv[index+1]:null;
if(!sourceDir&&!process.argv.includes('--fetch'))throw Error('Use --source-dir PATH or --fetch. Scores are already bundled.');
const sha=b=>createHash('sha256').update(b).digest('hex');
const output=path.join(root,'public/piano/focus-7.38');
await fs.mkdir(output,{recursive:true});
const scores=[],report=[];
for(const track of manifest.tracks){
 let events,bpm=track.bpm,timeScale=1,sourceDuration=null;
 if(track.sourceType==='ready-midi'){
  let bytes;
  if(sourceDir)bytes=await fs.readFile(path.join(sourceDir,track.inputFile));
  else{
   const res=await fetch(track.downloadUrl,{signal:AbortSignal.timeout(30000)});
   if(!res.ok)throw Error('Download failed: '+track.title+' / '+res.status);
   bytes=new Uint8Array(await res.arrayBuffer());
  }
  if(sha(bytes)!==track.sourceSha256)throw Error('Source checksum mismatch: '+track.title);
  const parsed=parseMidi(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),track.parseOptions);
  sourceDuration=parsed.duration;bpm=parsed.bpm;
  if(track.fitTo30){
   timeScale=30/parsed.duration;bpm=+(parsed.bpm/timeScale).toFixed(4);
   events=parsed.events.map(n=>({...n,time:n.time*timeScale,duration:n.duration*timeScale}));
  }else{
   if(parsed.duration<(track.clipStart||0)+30)throw Error('Source shorter than selected clip: '+track.title);
   events=clipEvents(parsed.events,track.clipStart||0,30);
  }
 }else{
  let beat=0;events=[];
  for(const bar of track.bars){
   if(Math.abs(bar.reduce((s,n)=>s+n[1],0)-(track.beatsPerBar||4))>1e-8)throw Error('Invalid bar: '+track.title);
   for(const [midi,length] of bar){
    if(midi!==null)events.push({midi,time:beat*60/bpm,duration:length*60/bpm,velocity:.76,hand:'right'});
    beat+=length;
   }
  }
  if(Math.abs(beat*60/bpm-30)>.00001)throw Error('Educational excerpt must last 30 seconds: '+track.title);
 }
 // The parser's minimum sounding note is 30 ms. Drop a clipped edge fragment
 // shorter than that instead of letting MIDI re-import extend it past 30 s.
 events=events.filter(n=>30-n.time>=.032).map(n=>({...n,midi:n.midi+(track.transpose||0),duration:Math.min(n.duration,30-n.time)}));
 if(events.length<20||guideGroups(events,'right').length<15)throw Error('Insufficient melody: '+track.title);
 const midi=encodeMidi(events,{tempo:bpm});
 // Re-read the downloadable MIDI so the lesson and export use identical notes.
 const final=parseMidi(midi.buffer,{channelHands:{0:'right',1:'left'}}).events;
 const rows=final.map(n=>[+n.time.toFixed(5),n.midi,+n.duration.toFixed(5),+n.velocity.toFixed(5)]);
 const {bars,inputFile,downloadUrl,parseOptions,sourceDocumentUrl,sourceSha256,sourceMd5,clipStart,fitTo30,transpose,beatsPerBar,rhythm,...metadata}=track;
 scores.push({...metadata,kind:'ready',duration:30,bpm:+bpm.toFixed(2),difficulty:'O‘rta',
  credit:track.sourceCredit,sourceLabel:track.sourceType==='ready-midi'?'Tayyor MIDI manbasi':'Nota manbasi',
  arrangementLabel:track.sourceType==='ready-midi'?'Tayyor MIDI · melodiya':'Notadan tayyorlangan',
  sourceMidi:'/piano/focus-7.38/'+track.id+'.mid',rows});
 await fs.writeFile(path.join(output,track.id+'.mid'),midi);
 report.push({id:track.id,title:track.title,sourceType:track.sourceType,sourceUrl:track.sourceUrl,
  sourceSha256:track.sourceSha256||null,sourceMd5:track.sourceMd5||null,sourceCredit:track.sourceCredit,
  sourceDocumentUrl:track.sourceDocumentUrl||null,section:track.section||null,
  sourceDuration,clipStart:track.clipStart||0,timeScale,transpose:track.transpose||0,
  rhythm:track.rhythm||'source',clipLength:30,notes:final.length,rightHandSteps:guideGroups(final,'right').length,
  clipSha256:sha(midi),clipBytes:midi.length,bpm:+bpm.toFixed(2),melodyOnly:true,generatedAccompaniment:false});
}
await fs.writeFile(path.join(root,'src/piano-focus-ready.js'),
 '// Generated by scripts/build-focus-piano.mjs. Sources: data/piano-focus-7.38.json.\n'
 +'// Short melody lessons; composition and arrangement rights remain with their holders.\n'
 +'const scores='+JSON.stringify(scores)+';\n'
 +"export const FOCUS_SONGS=scores.map(({rows,...track})=>({...track,events:rows.map(([time,midi,duration,velocity])=>({time,midi,duration,velocity,hand:'right'}))}));\n");
await fs.writeFile(path.join(output,'manifest.json'),JSON.stringify({checkedAt:manifest.checkedAt,rights:manifest.rights,tracks:report},null,2)+'\n');
console.log(JSON.stringify({tracks:scores.length,notes:report.reduce((s,t)=>s+t.notes,0),midiBytes:report.reduce((s,t)=>s+t.clipBytes,0),report}));
